// Generates src/shared/ids.generated.ts from the installed game's data package:
// typed id maps for skills, items, every skill's recipes, enemies, combat areas and currencies.
//   bun run gen:ids
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readGameData } from './gamedata.ts';
import { ROOT } from './paths.ts';

const data = readGameData();
const ns: string = data.Namespace;
const objects: Record<string, any[]> = data.Objects;
const config: Record<string, Record<string, unknown>> = data.EntityConfig;

const nameOf = new Map<string, string>();
for (const list of Object.values(objects)) {
  if (!Array.isArray(list)) continue;
  for (const o of list) {
    if (!o?.Id) continue;
    const dn = o.DisplayName;
    const name = typeof dn === 'string' ? dn : (dn?.Singular ?? dn?.Text);
    if (name) nameOf.set(`${ns}:${o.Id}`, name);
  }
}

/** EntityConfig lists hold { Priority, Id } entries; object lists hold plain ids. */
const idOf = (x: unknown): string => (typeof x === 'string' ? x : String((x as { Id?: string })?.Id));
const full = (x: unknown) => {
  const id = idOf(x);
  return id.includes(':') ? id : `${ns}:${id}`;
};
const key = (id: string) => {
  const local = id
    .split(':')
    .pop()!
    .replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(local) ? `_${local}` : local;
};

function block(constName: string, doc: string, ids: unknown[]): string {
  const seen = new Set<string>();
  const lines = [...new Set(ids.map(full))].map((id) => {
    let k = key(id);
    while (seen.has(k)) k += '_';
    seen.add(k);
    const name = nameOf.get(id);
    return `  ${name ? `/** ${name.replace(/\*\//g, '')} */\n  ` : ''}${k}: '${id}',`;
  });
  return `/** ${doc} */\nexport const ${constName} = {\n${lines.join('\n')}\n} as const;\nexport type ${constName.replace(/s$/, '')}Id = (typeof ${constName})[keyof typeof ${constName}];\n`;
}

const out: string[] = [`// Generated by tools/gen-ids.ts from the installed game's ${ns}.json. Do not edit.\n`];

// Skills = entities with mastery tasks or recipes (every leveled entity has a MasteryGuild).
const skills = Object.keys(config).filter((id) => 'MasteryGuildTasks' in config[id]! || 'Recipes' in config[id]!);
out.push(block('Skills', 'Skill ids (use with m.skills / skill.start).', skills));

for (const [entity, cfg] of Object.entries(config)) {
  const recipes = cfg.Recipes;
  if (!Array.isArray(recipes) || recipes.length === 0) continue;
  const skill = entity.split(':').pop()!;
  out.push(block(`${skill}Recipes`, `${skill} recipes (skill.start targets).`, recipes));
}

const areas = (config[`${ns}:Combat`]?.Areas as unknown[] | undefined) ?? objects.CombatArea!.map((a) => a.Id);
out.push(block('CombatAreas', 'Combat areas (combat.fight).', areas));
out.push(
  block(
    'Enemies',
    'Enemies (combat.fight).',
    objects.Enemy!.map((e) => e.Id),
  ),
);
out.push(
  block(
    'Currencies',
    'Currencies (state.currencies keys).',
    objects.Currency!.map((c) => c.Id),
  ),
);
out.push(
  block(
    'Items',
    'Every item (state.bank keys).',
    objects.Item!.map((i) => i.Id),
  ),
);

/** Which enemies each area has, for checking a fight before sending it. */
const areaEnemies: Record<string, string[]> = {};
for (const a of objects.CombatArea ?? []) if (Array.isArray(a.Enemies)) areaEnemies[full(a.Id)] = a.Enemies.map(full);
out.push(
  `/** Enemies in each combat area. */\nexport const AreaEnemies: Record<string, readonly string[]> = ${JSON.stringify(areaEnemies)};\n`,
);

const file = join(ROOT, 'src', 'shared', 'ids.generated.ts');
writeFileSync(file, out.join('\n'));
console.log(`wrote ${file}: ${skills.length} skills, ${objects.Item!.length} items, ${objects.Enemy!.length} enemies`);
